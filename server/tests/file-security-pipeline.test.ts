import assert from 'node:assert';
import {
  fileSecurityService,
  FileSecurityValidationError,
} from '../src/shared/services/fileSecurity.service.js';

console.log('🧪 Starting 5-Layer File Upload Security Pipeline Test Suite...\n');

async function runTests() {
  // Test 1: Empty 0-byte Buffer
  console.log('1. Testing 0-byte buffer rejection...');
  await assert.rejects(
    async () => {
      await fileSecurityService.verifyFile(Buffer.alloc(0), {
        declaredFilename: 'empty.pdf',
        declaredMimeType: 'application/pdf',
      });
    },
    (err: any) => {
      assert.strictEqual(err.name, 'FileSecurityValidationError');
      assert.match(err.message, /empty \(0 bytes\)/);
      return true;
    },
    'Must reject 0-byte file'
  );
  console.log('   ✅ PASS: 0-byte buffer strictly rejected');

  // Test 2: Fake Extension Detection (file-type magic byte mismatch)
  console.log('2. Testing Fake Extension Detection (file-type)...');
  const fakePdfWithPlainText = Buffer.from('This is a text document pretending to be a PDF.');
  await assert.rejects(
    async () => {
      await fileSecurityService.verifyFile(fakePdfWithPlainText, {
        declaredFilename: 'spoofed_document.pdf',
        declaredMimeType: 'application/pdf',
      });
    },
    (err: any) => {
      assert.strictEqual(err.name, 'FileSecurityValidationError');
      assert.match(err.message, /Unsupported or corrupted file format/);
      return true;
    },
    'Must reject text document disguised as PDF'
  );

  // Minimal valid PNG generated by sharp:
  const pngValid = await (await import('sharp')).default({
    create: {
      width: 10,
      height: 10,
      channels: 4,
      background: { r: 255, g: 0, b: 0, alpha: 1 },
    },
  }).png().toBuffer();

  // Renaming PNG to .pdf (Spoofed extension)
  await assert.rejects(
    async () => {
      await fileSecurityService.verifyFile(pngValid, {
        declaredFilename: 'renamed_image.pdf',
        declaredMimeType: 'application/pdf',
      });
    },
    (err: any) => {
      assert.strictEqual(err.name, 'FileSecurityValidationError');
      assert.match(err.message, /Fake extension detected/);
      return true;
    },
    'Must catch extension spoofing (PNG renamed to PDF)'
  );
  console.log('   ✅ PASS: Fake extensions and spoofed MIME types detected and blocked');

  // Test 3: Image Integrity & Sanitization (Sharp)
  console.log('3. Testing Image Integrity & Raster Verification (Sharp)...');
  const validPngResult = await fileSecurityService.verifyFile(pngValid, {
    declaredFilename: 'valid_icon.png',
    declaredMimeType: 'image/png',
  });
  assert.strictEqual(validPngResult.verifiedExt, 'png');
  assert.strictEqual(validPngResult.verifiedMime, 'image/png');
  assert.strictEqual(validPngResult.metadata.width, 10);
  assert.strictEqual(validPngResult.metadata.height, 10);
  assert.ok(validPngResult.sanitizedBuffer.length > 0);

  // Image with valid PNG magic bytes but corrupted IHDR header
  const corruptedPng = Buffer.from(
    '89504e470d0a1a0a0000000d49484452000000000000000008060000005a396229',
    'hex'
  );
  await assert.rejects(
    async () => {
      await fileSecurityService.verifyFile(corruptedPng, {
        declaredFilename: 'corrupted.png',
        declaredMimeType: 'image/png',
      });
    },
    (err: any) => {
      assert.strictEqual(err.name, 'FileSecurityValidationError');
      assert.match(err.message, /Image integrity check failed/);
      return true;
    },
    'Must reject corrupted image data'
  );
  console.log('   ✅ PASS: Image integrity verified and sanitized via Sharp');

  // Test 4: PDF Integrity & Structure (PDF.js)
  console.log('4. Testing PDF Integrity & Page Parsing (PDF.js)...');
  const validMinimalPdf = Buffer.from(
    '%PDF-1.4\n1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj\n2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj\n3 0 obj<</Type/Page/MediaBox[0 0 100 100]/Parent 2 0 R>>endobj\nxref\n0 4\n0000000000 65535 f \n0000000009 00000 n \n0000000052 00000 n \n0000000106 00000 n \ntrailer<</Size 4/Root 1 0 R>>\nstartxref\n178\n%%EOF'
  );
  const validPdfResult = await fileSecurityService.verifyFile(validMinimalPdf, {
    declaredFilename: 'quotation.pdf',
    declaredMimeType: 'application/pdf',
  });
  assert.strictEqual(validPdfResult.verifiedExt, 'pdf');
  assert.strictEqual(validPdfResult.verifiedMime, 'application/pdf');
  assert.strictEqual(validPdfResult.metadata.pages, 1);

  // Malformed PDF structure
  const malformedPdf = Buffer.from('%PDF-1.4\nMalformed xref and header without trailer');
  await assert.rejects(
    async () => {
      await fileSecurityService.verifyFile(malformedPdf, {
        declaredFilename: 'broken.pdf',
        declaredMimeType: 'application/pdf',
      });
    },
    (err: any) => {
      assert.strictEqual(err.name, 'FileSecurityValidationError');
      return true;
    },
    'Must reject structurally broken PDF'
  );
  console.log('   ✅ PASS: PDF integrity & page structure verified via PDF.js');

  // Test 5: ClamAV Integration & Status
  console.log('5. Testing ClamAV Integration...');
  assert.ok(
    ['CLEAN', 'SKIPPED_UNAVAILABLE'].includes(validPdfResult.metadata.antivirusStatus),
    'Antivirus scan status must be recorded'
  );
  console.log('   ✅ PASS: Antivirus scan integrated cleanly (status: ' + validPdfResult.metadata.antivirusStatus + ')');

  console.log('\n🎉 ALL 5 SECURITY LAYERS (Multer, file-type, Sharp, PDF.js, ClamAV) PASSED VERIFICATION!\n');
}

runTests().catch((err) => {
  console.error('Test Suite Failed:', err);
  process.exit(1);
});
